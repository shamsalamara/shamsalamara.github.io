function applyCeoLanguage() {
  const I = window.SA_I18N;
  const content = ceoContent[I.lang];
  document.title = `${content.title} — Shams Al Amara`;
  document.querySelector('.detail-back').childNodes[0].nodeValue = `${I.common.back} `;
  document.querySelector('#ceo-page-kicker').textContent = content.kicker;
  document.querySelector('#ceo-page-title').textContent = content.title;
  document.querySelector('.ceo-page-portrait img').alt = content.imageAlt;
  document.querySelector('#ceo-page-text').replaceChildren(...content.paragraphs.map(value => {
    const paragraph = document.createElement('p');
    paragraph.textContent = value;
    return paragraph;
  }));
}

applyCeoLanguage();
document.addEventListener('sa:languagechange', applyCeoLanguage);
